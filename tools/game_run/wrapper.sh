# The Wine wrapper and the launcher.log check, part of the game-run library (sourced by lib.sh).
#
# The launcher rewrites the game directory (ddraw.dll, version.dll, ...) on every launch, so a driver that wants its own DLL
# in the game directory cannot install it before launch.sh runs.  The launcher honours EMPIRE_EARTH_WINE; the wrapper is the
# "wine" it is given.  It forwards everything to the real Wine and, only for the call that starts the game (`start /unix`),
# first runs the driver's hook (which puts the DLL in place).
#
# The launcher derives more from the path it is given than the wine binary: it finds Wine's own version.dll at
# <dirname wine>/../lib/wine/i386-windows/version.dll (apply-launch-patches.sh install_version_shim), puts <dirname wine> first
# on PATH (wineboot, winecfg, ...) and starts <dirname wine>/wineserver.  So the wrapper directory mirrors the Wine root: bin/
# holds a link to every tool of the real bin/ except wine itself, and every other top-level entry (lib, share, ...) is linked.

GR_WRAPPED_WINE=""

# <wrapper dir> <hook command words...>.  Sets GR_WRAPPED_WINE.  The hook runs, with the driver still alive and holding the
# lock, right before the game starts; if it fails, or the driver is gone, the start is refused (exit 97): an orphaned
# launcher, left running after its driver died, can then neither swap anything in nor start the game.
gr_make_wine_wrapper() {
  local dir="$1" entry name hook="" word owner_lstart
  shift
  for word in "$@"; do
    hook="$hook $(printf '%q' "$word")"
  done
  rm -rf "$dir"
  mkdir -p "$dir/bin" || return 1
  for entry in "$GR_WINE_ROOT"/*; do
    name="$(basename "$entry")"
    [ "$name" = bin ] && continue
    ln -s "$entry" "$dir/$name" || return 1
  done
  for entry in "$GR_WINE_ROOT"/bin/*; do
    name="$(basename "$entry")"
    [ "$name" = wine ] && continue
    ln -s "$entry" "$dir/bin/$name" || return 1
  done
  owner_lstart="$(gr_proc_lstart "$GR_OWNER_PID")"
  cat >"$dir/bin/wine" <<WRAP
#!/bin/bash
# Generated by gr_make_wine_wrapper (tools/game_run/wrapper.sh).  Do not edit.
if [ "\${1:-}" = start ] && [ "\${2:-}" = /unix ]; then
  owner_pid=$GR_OWNER_PID
  owner_lstart=$(printf '%q' "$owner_lstart")
  lock=$(printf '%q' "$GAME_RUN_LOCK")
  if ! kill -0 "\$owner_pid" 2>/dev/null \\
    || [ "\$(LC_ALL=C ps -o lstart= -p "\$owner_pid" 2>/dev/null | sed 's/^ *//; s/ *\$//')" != "\$owner_lstart" ] \\
    || ! grep -q "^pid=\$owner_pid\\\$" "\$lock/owner" 2>/dev/null; then
    echo "game-run wrapper: the driver (pid \$owner_pid) no longer holds the game-run lock; refusing to put anything in place or to start the game" >&2
    exit 97
  fi
  $hook || { echo "game-run wrapper: the start hook failed; not starting the game" >&2; exit 97; }
fi
exec $(printf '%q' "$GR_WINE_ROOT/bin/wine") "\$@"
WRAP
  chmod +x "$dir/bin/wine"
  GR_WRAPPED_WINE="$dir/bin/wine"
}

GR_LAUNCHER_LOG_MARK=0

# Remember how long launcher.log is, so that only the lines of this run are judged.
gr_launcher_log_mark() {
  GR_LAUNCHER_LOG_MARK="$(wc -l <"$GR_LOG_DIR/launcher.log" 2>/dev/null | tr -d ' ')"
  : "${GR_LAUNCHER_LOG_MARK:=0}"
}

# The launcher skips the version.dll shim silently when it cannot find Wine's copy; that is a different game than the one the
# user plays.  Fail unless this run's lines of launcher.log say the shim was installed, and record the hashes of the two DLLs.
gr_check_launcher_log() {
  local new rc=0
  new="$(tail -n +$((GR_LAUNCHER_LOG_MARK + 1)) "$GR_LOG_DIR/launcher.log" 2>/dev/null)"
  if printf '%s\n' "$new" | grep -q 'version.dll shim not installed'; then
    gr_log "FAIL: the launcher did not install the version.dll shim: $(printf '%s\n' "$new" | grep 'version.dll shim not installed' | head -1 | cut -c1-240)"
    rc=1
  elif ! printf '%s\n' "$new" | grep -q 'Installed the version.dll shim'; then
    gr_log "FAIL: launcher.log does not say that the version.dll shim was installed in this run"
    rc=1
  fi
  local f
  for f in version.dll version_eeorig.dll; do
    if [ -f "$GR_GAME/$f" ]; then
      gr_log "sha256 $f $(shasum -a 256 "$GR_GAME/$f" | cut -c1-64)"
    else
      gr_log "$f is not in the game directory"
    fi
  done
  return "$rc"
}
