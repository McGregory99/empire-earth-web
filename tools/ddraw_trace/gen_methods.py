#!/usr/bin/env python3
"""Generate src/methods.inc: the method tables of the five wrapped COM interfaces.

The tables come from the mingw-w64 SDK headers (ddraw.h, d3d.h), so slot order and
argument counts are the SDK's, not hand-typed.  The argument count decides how many bytes a
stdcall thunk pops, so a mistake here would corrupt the stack; hence the generator and the
`check-methods` Makefile target that regenerates and compares.

Usage: gen_methods.py <include-dir> [--check <methods.inc>]
"""
import re
import sys
from pathlib import Path

# (enum tag, C interface name, header)
INTERFACES = [
    ("DD7", "IDirectDraw7", "ddraw.h"),
    ("D3D7", "IDirect3D7", "d3d.h"),
    ("DEV7", "IDirect3DDevice7", "d3d.h"),
    ("SURF7", "IDirectDrawSurface7", "ddraw.h"),
    ("VB7", "IDirect3DVertexBuffer7", "d3d.h"),
]

METHOD_RE = re.compile(
    r"STDMETHOD(?:_\(\s*\w+\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS_?\s*(.*?)\)\s*PURE\s*;", re.S)


def split_args(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S).strip()
    if not text:
        return []
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [a.strip() for a in out]


def parse_arg(arg):
    arg = re.sub(r"\bconst\b|\bstruct\b", " ", arg)
    m = re.match(r"^(.*?)(\w+)\s*$", " ".join(arg.split()))
    if not m:
        raise SystemExit("cannot parse argument: %r" % arg)
    ctype = re.sub(r"\s+", "", m.group(1))
    return ctype, m.group(2)


def interface_block(text, name):
    start = text.index("DECLARE_INTERFACE_(%s," % name)
    body = text[text.index("{", start):text.index("};", start)]
    return body


def generate(include_dir):
    lines = ["/* GENERATED by gen_methods.py from the mingw-w64 ddraw.h and d3d.h. Do not edit. */"]
    for tag, name, header in INTERFACES:
        text = (Path(include_dir) / header).read_text(errors="replace")
        parsed = []
        for m in METHOD_RE.finditer(interface_block(text, name)):
            full = m.group(0)
            if full.startswith("STDMETHOD_"):
                mm = re.match(r"STDMETHOD_\(\s*(\w+)\s*,\s*(\w+)\s*\)", full)
                ret, mname = mm.group(1), mm.group(2)
            else:
                ret, mname = "HRESULT", m.group(2)
            args = [parse_arg(a) for a in split_args(m.group(3))]
            parsed.append((mname, ret, args))
        lines.append('DDT_IFACE(%s, "%s", %d)' % (tag, name, len(parsed)))
        for slot, (mname, ret, args) in enumerate(parsed):
            flat = ",".join('"%s","%s"' % (t, n) for t, n in args)
            lines.append('DDT_METHOD(%s, %d, %s, %d, (%s))' % (tag, slot, mname, len(args), flat))
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 2:
        raise SystemExit(__doc__)
    out = generate(argv[1])
    if len(argv) >= 4 and argv[2] == "--check":
        have = Path(argv[3]).read_text()
        if have != out:
            sys.stderr.write("methods.inc is stale; run `make gen-methods`\n")
            return 1
        return 0
    sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
