#!/usr/bin/env python3
"""Generate src/methods.inc and src/names.inc from the mingw-w64 SDK headers.

methods.inc: the method tables of the five wrapped COM interfaces.  Slot order and argument counts are
the SDK's, not hand-typed.  The argument count decides how many bytes a stdcall thunk pops, so a mistake
there would corrupt the stack; hence the generator and the `check-tables` Makefile target that
regenerates and compares.

names.inc: HRESULT names (DDERR_*, D3DERR_*) and the enumerations the trace prints by name (render
states, texture stage states, transform states, primitive types, light types).  The C side refers to the
SDK constants themselves, so the values can never drift from the headers.

Usage: gen_tables.py <include-dir> <out-dir> [--check]
"""
import re
import sys
from pathlib import Path

# (enum tag, C interface name, header)
INTERFACES = [
    ("DD7", "IDirectDraw7", "ddraw.h"),
    ("D3D7", "IDirect3D7", "d3d.h"),
    ("DEV7", "IDirect3DDevice7", "d3d.h"),
    ("SURF7", "IDirectDrawSurface7", "ddraw.h"),
    ("VB7", "IDirect3DVertexBuffer7", "d3d.h"),
]

METHOD_RE = re.compile(
    r"STDMETHOD(?:_\(\s*\w+\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS_?\s*(.*?)\)\s*PURE\s*;", re.S)


def split_args(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S).strip()
    if not text:
        return []
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [a.strip() for a in out]


def parse_arg(arg):
    arg = re.sub(r"\bconst\b|\bstruct\b", " ", arg)
    m = re.match(r"^(.*?)(\w+)\s*$", " ".join(arg.split()))
    if not m:
        raise SystemExit("cannot parse argument: %r" % arg)
    ctype = re.sub(r"\s+", "", m.group(1))
    return ctype, m.group(2)


def interface_block(text, name):
    start = text.index("DECLARE_INTERFACE_(%s," % name)
    body = text[text.index("{", start):text.index("};", start)]
    return body


def generate(include_dir):
    lines = ["/* GENERATED by gen_methods.py from the mingw-w64 ddraw.h and d3d.h. Do not edit. */"]
    for tag, name, header in INTERFACES:
        text = (Path(include_dir) / header).read_text(errors="replace")
        parsed = []
        for m in METHOD_RE.finditer(interface_block(text, name)):
            full = m.group(0)
            if full.startswith("STDMETHOD_"):
                mm = re.match(r"STDMETHOD_\(\s*(\w+)\s*,\s*(\w+)\s*\)", full)
                ret, mname = mm.group(1), mm.group(2)
            else:
                ret, mname = "HRESULT", m.group(2)
            args = [parse_arg(a) for a in split_args(m.group(3))]
            parsed.append((mname, ret, args))
        lines.append('DDT_IFACE(%s, "%s", %d)' % (tag, name, len(parsed)))
        for slot, (mname, ret, args) in enumerate(parsed):
            flat = ",".join('"%s","%s"' % (t, n) for t, n in args)
            lines.append('DDT_METHOD(%s, %d, %s, %d, (%s))' % (tag, slot, mname, len(args), flat))
    return "\n".join(lines) + "\n"


def generate_names(include_dir):
    inc = Path(include_dir)
    lines = ["/* GENERATED by gen_tables.py from the mingw-w64 ddraw.h, d3d.h and d3dtypes.h. Do not edit. */"]
    seen = set()
    for header in ("ddraw.h", "d3d.h", "d3dtypes.h"):
        for m in re.finditer(r"^#define\s+((?:DDERR|D3DERR)_\w+)\s+MAKE_DD", (inc / header).read_text(errors="replace"), re.M):
            if m.group(1) not in seen:
                seen.add(m.group(1))
                lines.append("DDT_HR(%s)" % m.group(1))
    types = (inc / "d3dtypes.h").read_text(errors="replace")
    for macro, prefix in (("DDT_RS", "D3DRENDERSTATE_"), ("DDT_TSS", "D3DTSS_"),
                          ("DDT_XFORM", "D3DTRANSFORMSTATE_"), ("DDT_PT", "D3DPT_"), ("DDT_LIGHT", "D3DLIGHT_")):
        names = []
        for m in re.finditer(r"^\s*%s(\w+)\s*=\s*(\d+)\s*,?" % prefix, types, re.M):
            if m.group(1) not in names:
                names.append(m.group(1))
        for n in names:
            lines.append("%s(%s)" % (macro, n))
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 3:
        raise SystemExit(__doc__)
    outs = {"methods.inc": generate(argv[1]), "names.inc": generate_names(argv[1])}
    check = len(argv) >= 4 and argv[3] == "--check"
    status = 0
    for name, text in outs.items():
        path = Path(argv[2]) / name
        if check:
            if not path.exists() or path.read_text() != text:
                sys.stderr.write("%s is stale; run `make gen-tables`\n" % path)
                status = 1
        else:
            path.write_text(text)
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv))
